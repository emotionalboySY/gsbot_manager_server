const FARM_BY_KEY = new Map();
const FARM_BY_ALIAS = new Map();
for (let i = 0; i < FARMS.length; i++) {
    const farm = FARMS[i];
    FARM_BY_KEY.set(farm.key, farm);
    FARM_BY_ALIAS.set(farm.key, farm);
    for (let j = 0; j < farm.aliases.length; j++) {
        FARM_BY_ALIAS.set(normalizeAlias(farm.aliases[j]), farm);
    }
}

/** 농장 키 또는 별칭(초성 포함) → 농장. 못 찾으면 null. */
function farmOf(text) {
    return FARM_BY_ALIAS.get(normalizeAlias(text)) || null;
}

/** 해당 레벨에서 입장할 수 있는 농장 목록. 표에 있는 순서 그대로. */
function farmsForLevel(level) {
    const lev = Number(level);
    return FARMS.filter((farm) => lev >= farm.minLevel && lev <= farm.maxLevel);
}

/** 1회 입장 시 얻는 경험치가 해당 레벨 필요 경험치의 몇 %인지. 범위 밖이면 null. */
function pctAt(farm, level) {
    const pct = farm.pct[Number(level)];
    return pct === undefined ? null : pct;
}

/**
 * 1회 입장으로 얻는 경험치의 절대값.
 *
 * 원본이 소수점 셋째 자리까지 반올림된 %라 되돌린 절대값에도 0.1% 안팎의
 * 오차가 남는다. 입장 횟수를 세는 용도에는 영향이 없는 크기다.
 */
function expPerEntry(farm, level) {
    const pct = pctAt(farm, level);
    if (pct === null) return null;
    const levelExp = expForLevel(level);
    if (levelExp === null) return null;
    return Math.round((levelExp * pct) / 100);
}

/** 사용자에게 보여줄 별칭 안내 — 초성만 있는 것은 뺀다. */
function displayAliases(farm) {
    return farm.aliases.filter((alias) => !/^[ㄱ-ㅎ]+$/.test(alias));
}

