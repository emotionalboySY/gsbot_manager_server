const MIN_LEVEL = EXP_AMOUNT[0].lev;
const MAX_LEVEL = EXP_AMOUNT[EXP_AMOUNT.length - 1].lev;

// 레벨 → 필요 경험치. find 로 매번 훑으면 시뮬레이션 루프에서 레벨당 선형
// 탐색이 되므로 Map 으로 미리 세워 둔다.
const EXP_BY_LEVEL = new Map();
for (let i = 0; i < EXP_AMOUNT.length; i++) {
    EXP_BY_LEVEL.set(EXP_AMOUNT[i].lev, EXP_AMOUNT[i].exp);
}

// Lv.1 부터 해당 레벨까지의 누적 경험치. CUMULATIVE.get(lev) 는
// "lev 레벨을 달성하는 데 든 총 경험치"다.
const CUMULATIVE = new Map();
(function () {
    let total = 0;
    CUMULATIVE.set(MIN_LEVEL, 0);
    for (let i = 0; i < EXP_AMOUNT.length; i++) {
        total += EXP_AMOUNT[i].exp;
        CUMULATIVE.set(EXP_AMOUNT[i].lev + 1, total);
    }
})();

/** lev → lev+1 에 필요한 경험치. 표에 없는 레벨이면 null. */
function expForLevel(lev) {
    const exp = EXP_BY_LEVEL.get(Number(lev));
    return exp === undefined ? null : exp;
}

/** Lv.1 부터 lev 달성까지의 누적 경험치. 표에 없는 레벨이면 null. */
function cumulativeExp(lev) {
    const exp = CUMULATIVE.get(Number(lev));
    return exp === undefined ? null : exp;
}

/** from 레벨 0% 에서 to 레벨 0% 까지 필요한 경험치. */
function expBetween(from, to) {
    const a = cumulativeExp(from);
    const b = cumulativeExp(to);
    if (a === null || b === null) return null;
    return b - a;
}

